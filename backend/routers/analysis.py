# Video serving for debugger playback
# ---------------------------------------------------------------------------

@router.get("/video/{run_uuid}")
async def serve_original_video(run_uuid: str):
    """Serve the original video file for debugger playback."""
    _check_debugger_enabled()
    _validate_uuid(run_uuid)
    outputs_dir = _get_outputs_dir()
    run_dir = outputs_dir / run_uuid

    if not run_dir.exists():
        raise HTTPException(status_code=404, detail="Run directory not found")

    # Look for original.* file
    for f in run_dir.iterdir():
        if f.name.startswith("original") and f.is_file():
            return FileResponse(
                str(f),
                media_type="video/mp4",
                headers={"Accept-Ranges": "bytes"},
            )

    raise HTTPException(
        status_code=404,
        detail="Original video not found. Set KEEP_ORIGINAL_FOR_DEBUG=true to enable.",
    )
